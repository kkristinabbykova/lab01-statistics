def main():
    nb = json.loads(NB.read_text(encoding="utf-8"))
    done = 0
    cells = nb["cells"]
    for (anchor, start), text in TEXTS.items():
        k0 = next((k for k, c in enumerate(cells) if f'id="{anchor}"' in "".join(c["source"])), None)
        if k0 is None:
            continue
        for c in cells[k0:k0 + 4]:   # TODO лежит в ячейке с якорем или в одной из следующих
            src = "".join(c["source"])
            if c["cell_type"] != "markdown" or start not in src:
                continue
            # TODO-абзац: от «**TODO …» до конца абзаца (пустая строка или конец ячейки)
            pat = re.compile(r"\*\*" + re.escape(start) + r"[\s\S]*?(?=\n\n|\Z)(\n\n_Вопросы:_(\n- _.*_)+)?")
            src2, n = pat.subn(lambda m: text, src, count=1)
            if n:
                c["source"] = src2.splitlines(keepends=True)
                done += 1
                break
    NB.write_text(json.dumps(nb, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"вписано текстов: {done}")


if __name__ == "__main__":
    main()
